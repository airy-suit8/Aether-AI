/**
 * api.ts — the one client for the Aether AI backend.
 *
 * Every request goes through send(), the one request wrapper (Sprint 6, decision 6):
 *   401  the access token is renewed once from the refresh cookie and the request sent again;
 *        if that fails too, the app is told (setUnauthorizedHandler) and signs the user out
 *   429  "please wait", for as long as Retry-After says when the server sends it
 *   else the server's own detail, which for a server error ends with its reference id
 *
 * Paths, request bodies and replies are typed from the backend's OpenAPI schema
 * (api-schema.ts, generated by `npm run api-types`), so a renamed route or field breaks the
 * TypeScript build instead of the running app.
 */
import type { components, paths } from './api-schema'

export type Schemas = components['schemas']
export type Source = Schemas['Source']
export type Turn = Schemas['Turn']
export type SessionSummary = Schemas['SessionSummary']
export type DocumentRecord = Schemas['DocumentRecord']
export type DocumentStatus = Schemas['DocumentStatus']
export type DoneEvent = Schemas['DoneEvent']
export type Usage = Schemas['Usage']
export type AgentStep = Schemas['AgentStep']
export type StreamEvent = Schemas['TokenEvent'] | Schemas['DoneEvent'] | Schemas['ErrorEvent']
export type Mode = NonNullable<Schemas['ChatRequest']['mode']>
export type FeedbackValue = Schemas['FeedbackRequest']['feedback']

// ── Types read from the schema ──────────────────────────────────────────────

type ApiPath = keyof paths
type Method = 'get' | 'post' | 'patch' | 'delete'
type Operation<P extends ApiPath, M extends Method> = Exclude<paths[P][M], undefined>
/** The methods a path has in the schema. */
type MethodOf<P extends ApiPath> = { [M in Method]: [Operation<P, M>] extends [never] ? never : M }[Method]
type JsonOf<R> = R extends { content: { 'application/json': infer B } } ? B : never
/** The JSON body of a route's success reply (200, or 202 for an accepted upload). */
export type Reply<P extends ApiPath, M extends MethodOf<P>> = Operation<P, M> extends { responses: infer R }
  ? R extends { 200: infer Ok } ? JsonOf<Ok> : R extends { 202: infer Ok } ? JsonOf<Ok> : never
  : never
type PathParams<P extends ApiPath, M extends MethodOf<P>> = Operation<P, M> extends { parameters: { path: infer X } } ? X : never
type Body<P extends ApiPath, M extends MethodOf<P>, Media extends string> =
  Operation<P, M> extends { requestBody?: { content: infer C } } ? (C extends Record<Media, infer B> ? B : never) : never

/** FastAPI's error body: the same key as its validation errors, holding a sentence or a list of them. */
type ErrorBody = { [K in keyof Schemas['HTTPValidationError']]?: Schemas['HTTPValidationError'][K] | string }

// ── State ───────────────────────────────────────────────────────────────────

let currentToken: string | null = null
let onUnauthorized: (() => void) | null = null

export const SESSION_EXPIRED_MESSAGE = 'Session expired. Please log in again.'

/** An error the server reported. message is written for the person using the app. */
export class ApiError extends Error {
  readonly status: number

  constructor(message: string, status: number) {
    super(message)
    this.name = 'ApiError'
    this.status = status
  }
}

export function setToken(token: string | null): void {
  currentToken = token
}

/** Register what to do when the session cannot be renewed: the app signs out to the start page. */
export function setUnauthorizedHandler(handler: (() => void) | null): void {
  onUnauthorized = handler
}

// ── The request wrapper ─────────────────────────────────────────────────────

interface Options<P extends ApiPath, M extends MethodOf<P>> {
  params?: PathParams<P, M>
  json?: Body<P, M, 'application/json'>
  form?: URLSearchParams | FormData
  signal?: AbortSignal
  /** A route that needs no sign-in: its 401 is the server's answer, not an expired session */
  open?: boolean
}

/** The path with its {parameters} filled in, e.g. /api/v1/documents/{document_id} -> /api/v1/documents/7 */
function urlOf(path: string, params?: object): string {
  const values = (params ?? {}) as Record<string, string | number>
  return path.replace(/\{(\w+)\}/g, (_, name: string) => encodeURIComponent(String(values[name])))
}

function withToken(headers: HeadersInit | undefined): HeadersInit | undefined {
  if (!currentToken) return headers
  return { ...(headers as Record<string, string> | undefined), Authorization: `Bearer ${currentToken}` }
}

/**
 * Get a new access token with the refresh cookie the server set at sign-in (httpOnly, so this
 * code never sees it). Several requests that find the token expired share one renewal.
 * Resolves to true when a new token was set.
 */
let renewal: Promise<boolean> | null = null
function renewToken(): Promise<boolean> {
  renewal ??= fetch(urlOf('/api/v1/auth/refresh' satisfies ApiPath), { method: 'POST' })
    .then(async (res) => {
      if (!res.ok) return false
      const token: Reply<'/api/v1/auth/refresh', 'post'> = await res.json()
      setToken(token.access_token)
      return true
    })
    .catch(() => false)
    .finally(() => { renewal = null })
  return renewal
}

function detailOf(body: ErrorBody | null): string | null {
  const detail = body?.detail
  if (typeof detail === 'string') return detail
  if (Array.isArray(detail)) return detail.map((d) => d.msg).join('; ')
  return null
}

function waitMessage(res: Response): string {
  const header = res.headers?.get('Retry-After')
  const seconds = header == null ? NaN : /^\d+$/.test(header) ? Number(header) : Math.ceil((Date.parse(header) - Date.now()) / 1000)
  if (Number.isFinite(seconds) && seconds > 0) {
    return `Too many requests. Please wait ${seconds} second${seconds === 1 ? '' : 's'} and try again.`
  }
  return 'Too many requests. Please wait a moment and try again.'
}

/** The error to throw for a reply that is not a success. */
async function failure(res: Response, open: boolean): Promise<ApiError> {
  if (res.status === 401 && !open) {
    // The session could not be renewed: forget the token and tell the app, once
    if (currentToken) {
      currentToken = null
      onUnauthorized?.()
    }
    return new ApiError(SESSION_EXPIRED_MESSAGE, 401)
  }
  if (res.status === 429) return new ApiError(waitMessage(res), 429)
  const body: ErrorBody | null = await res.json().catch(() => null)
  return new ApiError(detailOf(body) ?? `The request failed (error ${res.status}). Please try again.`, res.status)
}

/** Send a request; resolve to the Response when it succeeded, or throw an ApiError. */
async function send<P extends ApiPath, M extends MethodOf<P>>(method: M, path: P, options: Options<P, M> = {}): Promise<Response> {
  const { params, json, form, signal, open = false } = options
  const init: RequestInit = { method: method.toUpperCase(), signal }
  if (json !== undefined) {
    init.headers = { 'Content-Type': 'application/json' }
    init.body = JSON.stringify(json)
  } else if (form instanceof URLSearchParams) {
    init.headers = { 'Content-Type': 'application/x-www-form-urlencoded' }
    init.body = form
  } else if (form) {
    init.body = form  // the browser sets the multipart boundary
  }
  const url = urlOf(path, params ?? undefined)
  const attempt = () => fetch(url, open ? init : { ...init, headers: withToken(init.headers) })

  const held = currentToken
  let res = await attempt()
  if (res.status === 401 && !open && held && await renewToken()) res = await attempt()
  if (res.ok) return res
  throw await failure(res, open)
}

/** send() and read the JSON reply, typed by the schema. */
async function request<P extends ApiPath, M extends MethodOf<P>>(method: M, path: P, options: Options<P, M> = {}): Promise<Reply<P, M>> {
  const res = await send(method, path, options)
  return res.json()
}

// ── Authentication ──────────────────────────────────────────────────────────

/** Create an account. The invite code is needed only when the server sets one. */
export function register(username: string, password: string, inviteCode = '') {
  const json: Schemas['UserRegister'] = inviteCode ? { username, password, invite_code: inviteCode } : { username, password }
  return request('post', '/api/v1/auth/register', { json, open: true })
}

/** Sign in. The reply's access token is kept for every later request. */
export async function login(username: string, password: string) {
  const fields: Pick<Schemas['Body_login_api_v1_auth_login_post'], 'username' | 'password'> = { username, password }
  const data = await request('post', '/api/v1/auth/login', { form: new URLSearchParams(fields), open: true })
  setToken(data.access_token)
  return data
}

/**
 * Sign in again from the refresh cookie, as after a page reload. Returns the token data, or
 * null when there is no valid cookie (signed out, or a week without use).
 */
export async function refreshSession() {
  try {
    const data = await request('post', '/api/v1/auth/refresh', { open: true })
    setToken(data.access_token)
    return data
  } catch (err) {
    if (err instanceof ApiError && err.status === 401) return null
    throw err
  }
}

/** Who is signed in: { username, created_at }. A reloaded page knows its token, not the name. */
export function getMe() {
  return request('get', '/api/v1/auth/me')
}

/** Sign out on the server too: it removes the refresh cookie, so a reload stays signed out. */
export function logout() {
  setToken(null)
  return request('post', '/api/v1/auth/logout', { open: true })
}

// ── Documents ───────────────────────────────────────────────────────────────

type UploadForm = Body<'/api/v1/upload', 'post', 'multipart/form-data'>

/**
 * Upload a document. The server accepts it (202) and reads it in the background: the reply has
 * its document_id, for getDocument, and replaces (an earlier file of the same name goes once it is read).
 */
export function uploadDocument(file: File) {
  const field: keyof UploadForm = 'file'
  const form = new FormData()
  form.append(field, file)
  return request('post', '/api/v1/upload', { form })
}

